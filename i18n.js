function vinciveGetLang(){
  return localStorage.getItem('vincive-lang') || 'en';
}

function vinciveApplyLanguage(lang){
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const entry = VINCIVE_I18N[key];
    if (entry && entry[lang] !== undefined) el.innerHTML = entry[lang];
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const entry = VINCIVE_I18N[key];
    if (entry && entry[lang] !== undefined) el.setAttribute('placeholder', entry[lang]);
  });

  const titleKey = document.documentElement.getAttribute('data-i18n-page-title');
  if (titleKey && VINCIVE_I18N[titleKey] && VINCIVE_I18N[titleKey][lang]){
    document.title = VINCIVE_I18N[titleKey][lang].replace(/&amp;/g, '&');
  }

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('is-active', btn.dataset.lang === lang);
  });

  localStorage.setItem('vincive-lang', lang);
}

function vinciveInitLang(){
  const lang = vinciveGetLang();
  vinciveApplyLanguage(lang);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      const chosen = btn.dataset.lang;
      if (chosen !== vinciveGetLang()) vinciveApplyLanguage(chosen);
    });
  });
}

document.addEventListener('DOMContentLoaded', vinciveInitLang);
